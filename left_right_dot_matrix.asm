.MODEL SMALL
.DATA

; Sequence: H1E3R3

PATTERN DB 1111111B,0001000B,0001000B,0001000B,1111111B ; H
        DB 0000000B,1000010B,1111111B,1000000B,0000000B ; 1
        DB 1111111B,1001001B,1001001B,1001001B,1000001B ; E
        DB 0100010B,1000001B,1001001B,1001001B,0110110B ; 3
        DB 1111111B,0001001B,0011001B,0101001B,1000110B ; R
        DB 0100010B,1000001B,1001001B,1001001B,0110110B ; 3

SCREEN DB 30 DUP(0)

.CODE

START PROC

    MOV AX,@DATA
    MOV DS,AX

AGAIN:

    ; PATTERN -> SCREEN

    MOV SI,0
    MOV CX,30

COPY_DATA:

    MOV AL,PATTERN[SI]
    MOV SCREEN[SI],AL
    INC SI
    LOOP COPY_DATA


    ; DISPLAY

    MOV SI,0
    MOV DX,2000H
    MOV CX,30

DISPLAY:

    MOV AL,SCREEN[SI]
    OUT DX,AL

    INC SI
    INC DX

    LOOP DISPLAY


    ; DELAY

    MOV CX,300

DELAY1:

    LOOP DELAY1


    ; MOVE LEFT TO RIGHT
    ; SCREEN[0] -> SCREEN[1]
    ; SCREEN[1] -> SCREEN[2]
    ; ...
    ; SCREEN[28] -> SCREEN[29]

    MOV SI,29

SHIFT:

    MOV AL,SCREEN[SI-1]
    MOV SCREEN[SI],AL

    DEC SI
    JNZ SHIFT


    ; DISPLAY AGAIN

    MOV SI,0
    MOV DX,2000H
    MOV CX,30

DISPLAY2:

    MOV AL,SCREEN[SI]
    OUT DX,AL

    INC SI
    INC DX

    LOOP DISPLAY2


    ; DELAY

    MOV CX,300

DELAY2:

    LOOP DELAY2

    JMP AGAIN

START ENDP

END START