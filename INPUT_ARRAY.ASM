.MODEL SMALL
.STACK 100H
.DATA
ARR DW 100 DUP (?)
NEW_LINE DB 0AH,0DH,'$'
.CODE
MAIN PROC
    MOV AX,@DATA
    MOV DS,AX

    CALL INDEC
    MOV CX,AX
    MOV SI,0

    INPUT:
        CALL INDEC
        MOV ARR[SI],AX 
        INC SI
        INC SI

        MOV AH,9
        LEA DX,NEW_LINE
        INT 21H
    LOOP INPUT

    MOV AH,4CH
    INT 21H
MAIN ENDP
INCLUDE INDEC.ASM
INCLUDE OUTDEC.ASM
END MAIN