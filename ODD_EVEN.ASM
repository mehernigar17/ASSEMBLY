.MODEL SMALL
.STACK 100H

.DATA
INPUT DB 7
MSG_ODD DB "ODD$"
MSG_EVEN DB "EVEN$"

.CODE
MAIN PROC

    MOV AX,@DATA
    MOV DS,AX

    XOR AX,AX

    MOV AL,INPUT
    MOV BL,2
    DIV BL

    CMP AH,0
    JNE PRINT_ODD

    LEA DX,MSG_EVEN
    MOV AH,9
    INT 21H
    JMP FINISH

PRINT_ODD:
    LEA DX,MSG_ODD
    MOV AH,9
    INT 21H

FINISH:
    MOV AH,4CH
    INT 21H

MAIN ENDP
END MAIN